"""Generates host/presets_generated.cpp: every runtime preset the forked
nullDC4Wii core reads, with nullDC4Wii's own defaults.

nullDC4Wii keeps its presets (g_*_preset globals + get_*_preset() getters)
in wii/main.cpp next to its menus. The fork does not use that front end, so
this script copies the definitions the core actually references, with the
same linkage (extern "C" or C++) and the same default values.

    python port/emu/tools/gen_presets.py <nullDC4Wii>/wii/main.cpp port/emu
"""
import os
import re
import sys

main_cpp, emu_root = sys.argv[1], sys.argv[2]
src = open(main_cpp, encoding="utf-8", errors="replace").read()

# --- symbols referenced by the fork (outside the generated file) -----------
used = set()
for root, _, files in os.walk(emu_root):
    if os.sep + "host" in root or "/host" in root:
        continue
    for f in files:
        if f.endswith((".cpp", ".h", ".c", ".inc")):
            text = open(os.path.join(root, f), encoding="utf-8", errors="replace").read()
            used.update(re.findall(r"\b(get_[a-z0-9_]+)\s*\(", text))
            used.update(re.findall(r"\b(g_[a-z0-9_]+(?:_preset|_hack|_debug|_layout)?)\b", text))

# --- walk main.cpp, tracking extern "C" { } blocks ----------------------------
lines = src.split("\n")
in_c = False
depth = 0
globals_ = {}   # name -> (type, init, is_c)
getters = {}    # name -> (body_line, is_c)
for line in lines:
    s = line.strip()
    if re.match(r'extern\s+"C"\s*\{', s):
        in_c = True
        depth = 1
        # one-line block: extern "C" { int get_x() { return g_x; } }
        rest = s[s.index("{") + 1:]
        depth += rest.count("{") - rest.count("}")
        m = re.search(r"(int|unsigned|u32|bool|float)\s+(get_[a-z0-9_]+)\s*\(\s*(void)?\s*\)\s*(\{[^{}]*\})", rest)
        if m:
            getters[m.group(2)] = (f"{m.group(1)} {m.group(2)}() {m.group(4)}", True)
        if depth <= 0:
            in_c = False
        continue
    if in_c:
        depth += s.count("{") - s.count("}")
        m = re.match(r"(int|unsigned|u32|bool|float)\s+(get_[a-z0-9_]+)\s*\(\s*(void)?\s*\)\s*(\{[^{}]*\})", s)
        if m:
            getters[m.group(2)] = (f"{m.group(1)} {m.group(2)}() {m.group(4)}", True)
        m = re.match(r"(int|unsigned|u32|bool|float)\s+(g_[a-z0-9_]+)\s*(=\s*[^;]+)?;", s)
        if m:
            globals_[m.group(2)] = (m.group(1), (m.group(3) or "= 0")[1:].strip(), True)
        if depth <= 0:
            in_c = False
        continue
    m = re.match(r"(int|unsigned|u32|bool|float)\s+(get_[a-z0-9_]+)\s*\(\s*(void)?\s*\)\s*(\{[^{}]*\})", s)
    if m:
        getters[m.group(2)] = (f"{m.group(1)} {m.group(2)}() {m.group(4)}", False)
    m = re.match(r"(?:static\s+)?(int|unsigned|u32|bool|float)\s+(g_[a-z0-9_]+)\s*(=\s*[^;]+)?;", s)
    if m and not s.startswith("static"):
        globals_.setdefault(m.group(2), (m.group(1), (m.group(3) or "= 0")[1:].strip(), False))


# Array globals: int g_x[N] = { ... };
arrays = {}
for m in re.finditer(r"^\s*(int|unsigned|u32)\s+(g_[a-z0-9_]+)\s*\[(\w+)\]\s*=\s*(\{[^}]*\})\s*;", src, re.M):
    arrays[m.group(2)] = (m.group(1), m.group(3), m.group(4))


def resolve(expr):
    """Numeric value for an enum constant / #define used as an initialiser."""
    expr = expr.strip()
    if re.fullmatch(r"-?(0x[0-9a-fA-F]+|\d+)[uUlL]*|true|false", expr):
        return expr
    m = re.search(r"\b" + re.escape(expr) + r"\s*=\s*(-?(?:0x[0-9a-fA-F]+|\d+))", src)
    if m:
        return m.group(1)
    m = re.search(r"#define\s+" + re.escape(expr) + r"\s+\(?(-?(?:0x[0-9a-fA-F]+|\d+))", src)
    if m:
        return m.group(1)
    return expr


need_getters = sorted(g for g in getters if g in used)
need_globals = set()
for g in need_getters:
    need_globals.update(re.findall(r"\b(g_[a-z0-9_]+)\b", getters[g][0]))
need_globals.update(g for g in globals_ if g in used)

missing = sorted(u for u in used if u.startswith("get_") and u.endswith(("_preset",)) and u not in getters)

out = []
out.append("// GENERATED by port/emu/tools/gen_presets.py from nullDC4Wii wii/main.cpp.")
out.append("// Runtime presets read by the forked core, with nullDC4Wii's defaults.")
out.append("// Edit the defaults in host/presets_overrides.cpp, not here.")
out.append('#include "types.h"')
out.append("")
for name in sorted(need_globals):
    if name in arrays:
        typ, size, init = arrays[name]
        out.append(f"{typ} {name}[{resolve(size)}] = {init};")
        continue
    if name not in globals_:
        continue
    typ, init, is_c = globals_[name]
    decl = f"{typ} {name} = {resolve(init)};"
    out.append(f'extern "C" {decl}' if is_c else decl)
out.append("")
for name in need_getters:
    body, is_c = getters[name]
    out.append(f'extern "C" {body}' if is_c else body)
out.append("")

dst = os.path.join(emu_root, "host", "presets_generated.cpp")
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(f"{len(need_getters)} getters, {len(need_globals)} globals -> {dst}")
if missing:
    print("referenced but not found in main.cpp:", " ".join(missing))
